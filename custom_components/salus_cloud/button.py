"""Button platform for Salus Cloud: OneTouch rules and a refresh of each thermostat's values."""

from __future__ import annotations

from typing import Any

from homeassistant.components.button import ButtonEntity
from homeassistant.core import HomeAssistant
from homeassistant.helpers.device_registry import DeviceInfo
from homeassistant.helpers.entity_platform import AddConfigEntryEntitiesCallback

from .const import DOMAIN
from .coordinator import SalusCloudCoordinator, SalusConfigEntry
from .entity import SalusEntity

PARALLEL_UPDATES = 0


async def async_setup_entry(
    hass: HomeAssistant,
    entry: SalusConfigEntry,
    async_add_entities: AddConfigEntryEntitiesCallback,
) -> None:
    """Set up OneTouch rules created by the user (rules generated by the Salus app are skipped) and refresh buttons."""
    coordinator = entry.runtime_data
    entities: list[ButtonEntity] = [
        SalusOneTouchButton(coordinator, rule)
        for rule in coordinator.rules
        if rule.get("rule_trigger_key") and not rule.get("rule", {}).get("name", "").startswith("_")
    ]
    entities.extend(
        SalusRefreshButton(coordinator, device, "refresh")
        for device in coordinator.data.values()
        if device.is_thermostat and device.refresh_command
    )
    async_add_entities(entities)


class SalusRefreshButton(SalusEntity, ButtonEntity):
    """Asks a thermostat to report all its values again, e.g. after a change made in the Salus app."""

    async def async_press(self) -> None:
        """Send the refresh command; the values arrive over the next half minute."""
        await self.coordinator.async_refresh_device(self._device_id)


class SalusOneTouchButton(ButtonEntity):
    """Button triggering a Salus OneTouch rule."""

    _attr_has_entity_name = False

    def __init__(self, coordinator: SalusCloudCoordinator, rule: dict[str, Any]) -> None:
        """Initialize the button."""
        self._coordinator = coordinator
        self._gateway_id = rule.get("_gateway_id", "")
        self._rule_trigger_key = rule["rule_trigger_key"]
        gateway = coordinator.get_gateway(self._gateway_id)
        rule_name = rule.get("rule", {}).get("name", "Unknown Rule")
        self._attr_name = f"{gateway.name if gateway else 'Salus'} {rule_name}"
        self._attr_unique_id = f"{DOMAIN}_{self._gateway_id}_onetouch_{rule.get('id', '')}"
        device_info = DeviceInfo(
            identifiers={(DOMAIN, f"{self._gateway_id}_onetouch_rules")},
            name="OneTouch Rules",
            manufacturer="Salus",
            model="OneTouch Rules",
        )
        coordinator.link_to_gateway(device_info, self._gateway_id)
        self._attr_device_info = device_info

    async def async_press(self) -> None:
        """Trigger the rule."""
        await self._coordinator.async_trigger_rule(self._gateway_id, self._rule_trigger_key)
